/* 체형 (사용자 요청) — 밀대 0~20, 10 이 기본. 옷도 같은 조각이라 몸과 함께 늘고 줄어 맞춰진다.
   - 다리 길이: 무릎 위만 늘린다 (발 · 신발 높이는 그대로). 엉덩이 높이가 바뀌면 위의 모든 것이 그만큼 오른다.
   - 상체 길이: 엉덩이(0.5)부터 어깨까지를 늘린다. 머리는 늘리지 않고 옮기기만.
   - 팔 길이: 어깨 돌쩌귀부터 아래로 늘린다.
   - 살찜: 몸통 · 다리는 폭과 깊이를, 팔은 조금 덜 굵힌다. 팔 · 다리 자리도 몸 폭만큼 바깥으로. */
const sl = (v, lo, hi) => lo + (hi - lo) * ((Number.isInteger(v) ? v : 10) / 20);
function shape(out, c, AX, LX){
  const Ls = sl(c.leg, 0.75, 1.3), Ts = sl(c.torso, 0.8, 1.25), As = sl(c.arm, 0.8, 1.22), fx = sl(c.fat, 0.82, 1.5);
  const fz = 1 + (fx - 1) * 0.85, fa = 1 + (fx - 1) * 0.55, fl = 1 + (fx - 1) * 0.8;
  const FOOT = 0.13, HIP = 0.5 * Ls;
  const low = y => y <= FOOT ? y : FOOT + (y - FOOT) * (HIP - FOOT) / (0.5 - FOOT);   // 다리 쪽 높이
  const up = y => y < 0.5 ? low(y) : HIP + (y - 0.5) * Ts;                            // 몸 쪽 높이
  const shY = up(0.9), headY = up(0.95), lift = headY - 0.95;
  const AXn = AX * fx, LXn = LX * fx;
  const res = out.map(([g, col, x, y, z, w, h, d, r, rz]) => {
    let y1 = y - h / 2, y2 = y + h / 2;
    if (g === 'head'){ y1 += lift; y2 += lift; }
    else if (g === 'body'){ y1 = up(y1); y2 = up(y2); x *= fx; w *= fx; z *= fz; d *= fz; }
    else if (g === 'armL' || g === 'armR'){
      const s = g === 'armL' ? -1 : 1;
      y1 = shY + (y1 - 0.9) * As; y2 = shY + (y2 - 0.9) * As;
      x = s * AXn + (x - s * AX) * fa; w *= fa; z *= fa; d *= fa;
    } else {
      const s = g === 'legL' ? -1 : 1;
      y1 = low(y1); y2 = low(y2);
      x = s * LXn + (x - s * LX) * fl; w *= fl; z *= fl; d *= fl;
    }
    return [g, col, x, (y1 + y2) / 2, z, w, y2 - y1, d, r, rz];
  });
  return { out: res, AX: AXn, LX: LXn, hipY: HIP, shY, headY, lift, handY: (0.52 - 0.9) * As, handZ: 0.005 * fa };
}

